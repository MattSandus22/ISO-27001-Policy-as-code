"""Statement of Applicability (ISO/IEC 27001:2022 clause 6.1.3 d)."""

from __future__ import annotations

import csv
import io
from dataclasses import dataclass

from .lint import addressed_controls
from .model import Workspace, control_ids, control_title, theme


@dataclass
class SoARow:
    control: str
    title: str
    theme: str
    applicable: bool
    justification: str
    policies: list[str]
    other: str

    @property
    def status(self) -> str:
        if not self.applicable:
            return "Excluded"
        return "Addressed" if (self.policies or self.other) else "Gap"


def build_soa(ws: Workspace) -> list[SoARow]:
    addressed = addressed_controls(ws)
    rows = []
    for cid in control_ids():
        e = ws.soa.get(cid, {})
        rows.append(SoARow(
            control=f"A.{cid}",
            title=control_title(cid),
            theme=theme(cid),
            applicable=e.get("applicable", True),
            justification=e.get("justification", ""),
            policies=sorted(addressed.get(cid, [])),
            other=e.get("addressed_by", ""),
        ))
    return rows


def to_csv(rows: list[SoARow]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["control", "title", "theme", "applicable", "status", "policies", "other_documents", "justification"])
    for r in rows:
        w.writerow([r.control, r.title, r.theme, "Yes" if r.applicable else "No", r.status,
                    "; ".join(r.policies), r.other, r.justification])
    return buf.getvalue()


def to_markdown(rows: list[SoARow], organization: str) -> str:
    out = [f"# Statement of Applicability: {organization}", "",
           "ISO/IEC 27001:2022 Annex A. Generated by policykit from the policy front matter and `soa.yaml`.", "",
           "| Control | Title | Applicable | Addressed by | Justification |",
           "|---|---|---|---|---|"]
    for r in rows:
        by = ", ".join(r.policies + ([r.other] if r.other else [])) or "**Gap**"
        out.append(f"| {r.control} | {r.title} | {'Yes' if r.applicable else 'No'} | "
                   f"{by if r.applicable else '—'} | {r.justification} |")
    out.append("")
    return "\n".join(out)
